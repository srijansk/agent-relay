"""Export a relay workflow to Claude Code's subagent + slash-command format.

Claude Code reads two folders out of any project:

  * ``.claude/agents/<name>.md`` — subagent definitions (frontmatter + body)
  * ``.claude/commands/<name>.md`` — custom slash commands

This exporter writes one subagent file per role and a small set of slash
commands that wrap the relay CLI. After running, a Claude Code user can
``/relay-next`` and ``/relay-advance`` from inside their session, or
delegate to a specific role using ``@role-name``.
"""

from __future__ import annotations

from pathlib import Path

import yaml

from relay.protocol.roles import RoleSpec
from relay.protocol.workflow import RoleDefinition, WorkflowDefinition


def export_to_claude_code(workflow_dir: Path, output_dir: Path) -> list[Path]:
    """Generate ``.claude/agents/`` + ``.claude/commands/`` from a workflow.

    Returns the list of files created.
    """
    workflow = _load_workflow(workflow_dir)
    created: list[Path] = []

    agents_dir = output_dir / ".claude" / "agents"
    commands_dir = output_dir / ".claude" / "commands"
    agents_dir.mkdir(parents=True, exist_ok=True)
    commands_dir.mkdir(parents=True, exist_ok=True)

    for role_name, role_def in workflow.roles.items():
        role = _load_role(workflow_dir, role_def)
        if role is None:
            continue
        agent_path = agents_dir / f"{role_name}.md"
        agent_path.write_text(_render_agent(role_name, role, role_def), encoding="utf-8")
        created.append(agent_path)

    for cmd_name, body in _SLASH_COMMANDS.items():
        cmd_path = commands_dir / f"{cmd_name}.md"
        cmd_path.write_text(body.strip() + "\n", encoding="utf-8")
        created.append(cmd_path)

    overview_path = agents_dir / "README.md"
    overview_path.write_text(_render_overview(workflow), encoding="utf-8")
    created.append(overview_path)

    return created


def _load_workflow(workflow_dir: Path) -> WorkflowDefinition:
    raw = yaml.safe_load((workflow_dir / "workflow.yml").read_text())
    return WorkflowDefinition.model_validate(raw)


def _load_role(workflow_dir: Path, role_def: RoleDefinition) -> RoleSpec | None:
    role_path = workflow_dir / role_def.rules
    if not role_path.exists():
        return None
    raw = yaml.safe_load(role_path.read_text())
    return RoleSpec.model_validate(raw)


def _render_agent(
    role_name: str, role: RoleSpec, role_def: RoleDefinition
) -> str:
    """Render a Claude Code subagent file: frontmatter + system prompt body."""
    description = role_def.description or f"{role_name.title()} agent"
    # Multi-line YAML safe-dump for the description avoids quoting noise.
    frontmatter = {
        "name": role_name,
        "description": description,
    }
    body_lines: list[str] = [
        "---",
        yaml.safe_dump(frontmatter, sort_keys=False).strip(),
        "---",
        "",
        f"# {role_name.title()} Agent",
        "",
        role.system_prompt.strip(),
        "",
        "## File ownership",
        "",
        f"- **Reads**: {', '.join(role_def.reads) if role_def.reads else 'none'}",
        f"- **Writes**: {', '.join(role_def.writes) if role_def.writes else 'none'}",
        "",
    ]
    if role.output_format:
        body_lines.extend(
            [
                "## Output format",
                "",
                role.output_format.strip(),
                "",
            ]
        )
    if role.verdict_field:
        body_lines.extend(
            [
                "## Verdict",
                "",
                (
                    f"Your output MUST include: `## {role.verdict_field}: "
                    f"{role.approve_value}` or `## {role.verdict_field}: "
                    f"{role.reject_value}`"
                ),
                "",
            ]
        )
    if role.inject_lessons:
        body_lines.extend(
            [
                "## Lessons",
                "",
                (
                    "If `.relay/LESSONS.md` exists in this repo, read it before "
                    "drafting. It contains role-typed lessons distilled from "
                    "past workflow runs — apply judgment, not blind imitation."
                ),
                "",
            ]
        )

    return "\n".join(body_lines).rstrip() + "\n"


def _render_overview(workflow: WorkflowDefinition) -> str:
    role_lines = [
        f"- `@{role_name}` — {role_def.description}"
        for role_name, role_def in workflow.roles.items()
    ]
    stage_lines = [
        f"- `{stage_name}`" + (f" → {_describe_next(stage)}" if not stage.terminal else " (terminal)")
        for stage_name, stage in workflow.stages.items()
    ]
    return (
        "# Relay agents for Claude Code\n\n"
        f"This folder was generated by `relay export claude-code` from "
        f"workflow `{workflow.name}`.\n\n"
        "## Subagents\n\n"
        + "\n".join(role_lines)
        + "\n\n## Stages\n\n"
        + "\n".join(stage_lines)
        + "\n\n## How to drive the workflow from Claude Code\n\n"
        "Use the slash commands in `.claude/commands/`:\n\n"
        "- `/relay-status` — print the current stage\n"
        "- `/relay-next` — print the prompt for the active role\n"
        "- `/relay-advance` — advance once the active role has written its artifact\n"
        "- `/relay-distill` — re-compile lessons from `.relay/history/`\n"
    )


def _describe_next(stage) -> str:
    nxt = stage.next
    if isinstance(nxt, str):
        return nxt
    if isinstance(nxt, dict):
        return ", ".join(f"{k}={v}" for k, v in nxt.items())
    return "?"


_SLASH_COMMANDS: dict[str, str] = {
    "relay-status": """
---
description: Print the current relay workflow state
---

Run `relay status` and report the stage, active role, and any iteration counters.
""",
    "relay-next": """
---
description: Print the prompt for the next relay agent
---

Run `relay next` to see the prompt for the active role. Then act as that
role: read the input artifacts named in the prompt, write your output to the
file the prompt specifies, and report when you're done.
""",
    "relay-advance": """
---
description: Advance the relay workflow after the active role finishes
---

Run `relay advance`. If the stage is branching, look at the verdict line in
the artifact you just wrote and pass it via `--verdict approve` or
`--verdict reject` if `relay advance` cannot detect it automatically.
""",
    "relay-distill": """
---
description: Compile lessons from past relay runs
---

Run `relay distill` to refresh `.relay/LESSONS.md` and `.relay/lessons.json`.
After it runs, summarise the count of new lessons by role and severity.
""",
}
